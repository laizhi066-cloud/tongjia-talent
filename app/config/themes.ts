export const DEFAULT_THEME_ID = 'emerald'

export function getTheme(id: string): ThemePreset | undefined {
  return themes.find(t => t.id === id)
}

/**
 * 将主题数据转为 CSS 变量键值对
 * @param theme 主题预设
 * @param dark 是否为暗色模式
 * @param radius 圆角值（默认 0.625rem）
 */
export function themeToCSSVars(theme: ThemePreset, dark: boolean, radius = '0.625rem'): Record<string, string> {
  const colors = dark ? theme.dark : theme.light
  const vars: Record<string, string> = { '--radius': radius }
  for (let i = 0; i < K.length; i++) {
    vars[K[i]!] = colors[i]!
  }
  return vars
}
